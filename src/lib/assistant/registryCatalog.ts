// THE CATALOG THE CLIENT READS (2026-11-06): the part of every tool's card that the phone's sheet, the desk panel
// and the Tasks list need — its label, its group, what it changes, whether it is a build (and its steps), whether it
// takes a PIN or runs at its own time — as plain data, written to lib/assistant/catalog.generated.ts by
// scripts/assistant-catalog.ts from the tools themselves. Pure: the generator and the registry check both call it.
import type { AnyTool, ToolEffect, ToolGroup } from "@/lib/assistant/tools";

export interface CatalogEntry {
  label: string;
  group: ToolGroup;
  effect: ToolEffect;
  kind: "read" | "write";
  /** A build: a draft made without a yes — "Working" while queued, "Ready" when done, its trace on the card. */
  build: boolean;
  steps: readonly string[] | null;
  /** Money: read back and waiting for the yes AND the person's PIN. */
  pin: boolean;
  /** Runs at its own time with no yes (a reminder to oneself): queued means set. */
  scheduled: boolean;
  version: number;
}

export type Catalog = Record<string, CatalogEntry>;

export function catalogFrom(tools: readonly AnyTool[]): Catalog {
  const out: Catalog = {};
  for (const t of tools) {
    const write = t.kind === "write";
    out[t.name] = {
      label: t.card.label,
      group: t.card.group,
      effect: t.card.effect,
      kind: t.kind,
      build: write && Boolean(t.instant),
      steps: t.card.steps ? [...t.card.steps] : null,
      pin: t.card.effect === "money",
      scheduled: write && t.scheduled === true,
      version: t.card.version,
    };
  }
  return out;
}

/** The generated file's text, stable for the same tools (keys in the tools' order, two-space JSON). */
export function catalogSource(catalog: Catalog): string {
  return [
    "// GENERATED by scripts/assistant-catalog.ts from the tools' cards (lib/assistant/tools) — do not edit by hand.",
    "// Run `npm run assistant:catalog` after adding or changing a tool; qa/tests/logic/assistant-registry.check.ts fails when this is stale.",
    'import type { Catalog } from "@/lib/assistant/registryCatalog";',
    "",
    `export const CATALOG: Catalog = ${JSON.stringify(catalog, null, 2)};`,
    "",
  ].join("\n");
}
